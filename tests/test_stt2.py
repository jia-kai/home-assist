def _cmvn_text(shift: float = -2.0, scale: float = 0.5) -> str:
    """Create a minimal valid 560-wide signed Kaldi normalization artifact.

    Args:
        shift:
            Signed additive shift repeated across all 560 features.

        scale:
            Positive multiplicative scale repeated across all features.

    """
    shifts = " ".join([str(shift)] * 560)
    scales = " ".join([str(scale)] * 560)
    return (
        f"<Nnet>\n<AddShift> 560 560\n<LearnRateCoef> 0 [ {shifts} ]\n"
        f"<Rescale> 560 560\n<LearnRateCoef> 0 [ {scales} ]\n</Nnet>\n"
    )


