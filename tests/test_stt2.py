class _Engine:
    """Tiny frame-ID fixture recording controls and resource release."""

    calls: list[tuple[tuple[int, ...], int, int]]
    """Observed feature shape, language and ITN controls for each inference."""

    closed: bool
    """Whether close has been requested."""

    profile_calls: int
    """Number of explicit counter-collection calls; zero for default transcription."""

    profile_path: Path | None = None
    """No durable trace is generated by this inference fixture."""

    def __init__(self) -> None:
        """Initialize an empty call log and unreleased fixture."""
        self.calls = []
        self.closed = False
        self.profile_calls = 0

    def infer(
        self, features: NDArray[np.float32], language_id: int, textnorm_id: int
    ) -> NDArray[np.int64]:
        """Emit a repeat separated by blank while retaining exact output frame count.

        Args:
            features:
                Normalized float32 feature matrix shaped (frames, 560).

            language_id:
                Prefix language embedding index to record.

            textnorm_id:
                Prefix normalization embedding index to record.

        """
        self.calls.append((features.shape, language_id, textnorm_id))
        result = np.zeros(features.shape[0] + 4, dtype=np.int64)
        result[:4] = [9, 9, 0, 9]
        return result

    def close(self) -> None:
        """Mark the fixture released without affecting already recorded calls."""
        self.closed = True

    def get_profile(self) -> list[NodeProfile]:
        """Return one copied fixture counter and record optional collection overhead."""
        self.profile_calls += 1
        return [
            NodeProfile(
                node_name="fixture",
                node_type="MatMul",
                execution_type="fixture_f32",
                status="EXECUTED",
                real_seconds=0.001,
                cpu_seconds=0.001,
            )
        ]


class _Tokenizer:
    """Mock actual decoding semantics rather than joining token strings."""

    ids: list[int]
    """Last sequence supplied to the decoder."""

    raw: str
    """Actual metadata-rich string returned by the fixture decoder."""

    def __init__(self) -> None:
        """Initialize a Chinese/English mixed metadata-rich decode."""
        self.ids = []
        self.raw = "<|zh|><|NEUTRAL|><|Speech|><|woitn|>你好， turn on lights!"

    def decode(self, ids: list[int]) -> str:
        """Record IDs and return the fixture's complete raw decode.

        Args:
            ids:
                Collapsed nonblank vocabulary sequence.

        """
        self.ids = ids
        return self.raw


def _mock_recognizer(
    monkeypatch: pytest.MonkeyPatch,
    directory: Path,
    language: str | None = None,
    use_itn: bool = False,
    backend: Backend = "cpu",
    profiling: bool = False,
    max_audio_seconds: float = 60.0,
) -> tuple[stt2.STT, _Engine, _Tokenizer]:
    """Construct a real frontend/manifest recognizer with tiny inference fixtures.

    Args:
        monkeypatch:
            Scoped pytest attribute replacement helper.

        directory:
            Fixture artifacts validated through the actual offline validator.

        language:
            Requested model language control or None for auto.

        use_itn:
            Requested text normalization prefix control.

        backend:
            Explicit cpu or GPU setting checked at the mocked engine boundary.

        profiling:
            Optional counter request setting checked at the mocked boundary.

        max_audio_seconds:
            Inclusive source-duration limit for validation-only fixture calls.

    """
    engine = _Engine()
    tokenizer = _Tokenizer()
    budget_calls: list[int] = []
    requested_backend = backend
    requested_profiling = profiling

    def make_engine(
        path: Path, threads: int, backend: Backend, profiling: bool
    ) -> _Engine:
        """Return the owned engine fixture and check constructor controls.

        Args:
            path:
                Validated graph artifact location.

            threads:
                Requested native inference thread count.

            backend:
                Exact requested plugin, without automatic fallback.

            profiling:
                Whether native execution counters should be enabled.

        """
        assert path == directory / "model.xml"
        assert threads == 1
        assert budget_calls == [1]
        assert backend == requested_backend
        assert profiling == requested_profiling
        return engine

    def configure_budget(threads: int) -> tuple[int, ...]:
        """Record construction-time budgeting without changing pytest's affinity.

        Args:
            threads:
                Exact one-core budget requested by the fixture recognizer.

        """
        budget_calls.append(threads)
        return tuple(range(threads))

    def make_tokenizer(path: Path) -> _Tokenizer:
        """Return the owned tokenizer fixture after checking its location.

        Args:
            path:
                Validated SentencePiece artifact location.

        """
        assert path == directory / "tokenizer.model"
        return tokenizer

    monkeypatch.setattr(stt2, "make_engine", make_engine)
    monkeypatch.setattr(stt2, "make_tokenizer", make_tokenizer)
    monkeypatch.setattr(stt2, "configure_cpu_budget", configure_budget)
    recognizer = stt2.STT(
        stt2.STTConfig(
            directory,
            threads=1,
            language=language,
            use_itn=use_itn,
            backend=backend,
            profiling=profiling,
            max_audio_seconds=max_audio_seconds,
        )
    )
    return recognizer, engine, tokenizer


def test_mel_bank_contract() -> None:
    """Check exact dimensions, nonnegative triangles and the zero Nyquist column."""
    weights = mel_filterbank()
    assert weights.shape == (80, 257)
    assert weights.dtype == np.float32
    assert np.all(weights >= 0)
    assert np.all(weights <= 1)
    assert np.count_nonzero(weights[:, -1]) == 0


@pytest.mark.parametrize(
    "samples,frames", [(400, 1), (559, 1), (560, 2), (719, 2), (720, 3)]
)
def test_complete_frame_count(
    identity_frontend: Frontend, samples: int, frames: int
) -> None:
    """Verify snip-edges framing and the exact float32 epsilon floor for silence.

    Args:
        identity_frontend:
            Zero-dither frontend with identity normalization.

        samples:
            Test waveform length in samples at 16 kHz.

        frames:
            Expected complete FBANK frame count.

    """
