def test_lfr_clips_both_edges() -> None:
    """Verify clip(6*j+k-3), including left repeats, stride and right repeats."""
    features = np.repeat(np.arange(8, dtype=np.float32)[:, None], 80, axis=1)
    stacked = stack_lfr(features).reshape(2, 7, 80)
    np.testing.assert_array_equal(
        stacked[:, :, 0], [[0, 0, 0, 0, 1, 2, 3], [3, 4, 5, 6, 7, 7, 7]]
    )
    assert stack_lfr(features[:1]).shape == (1, 560)
    with pytest.raises(ValueError, match="nonempty"):
        stack_lfr(features[:0])


