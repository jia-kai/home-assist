@pytest.mark.parametrize("sample_rate", [16000, 24000])
@pytest.mark.parametrize("channels", [1, 2])
def test_nonzero_pcm16_file_and_sample_scales_match(
    monkeypatch: pytest.MonkeyPatch,
    artifact_directory: Path,
    tmp_path: Path,
    sample_rate: int,
    channels: int,
) -> None:
    """Decode PCM16 and direct floats to identical features without extra scaling.

    Args:
        monkeypatch:
            Replaces inference and tokenization while using the real frontend.

        artifact_directory:
            Hashed fake model artifacts; no neural checkpoint is loaded.

        tmp_path:
            Isolated directory for the generated PCM16 WAV.

        sample_rate:
            Source rate in Hz, native or requiring polyphase resampling.

        channels:
            Mono or stereo PCM layout; stereo is averaged in normalized units.

    """
    recognizer, engine, _ = _mock_recognizer(monkeypatch, artifact_directory)
    infer = Mock(wraps=engine.infer)
    monkeypatch.setattr(engine, "infer", infer)
    pcm = np.random.default_rng(91).integers(
        -20000, 20000, size=(sample_rate // 10, channels), dtype=np.int16
    )
    pcm[:3, 0] = [-32768, -1, 32767]
    path = tmp_path / "scale.wav"
    stt2.sf.write(path, pcm, sample_rate, subtype="PCM_16")
    recognizer.transcribe(path)
    file_features = infer.call_args.args[0].copy()
    mono = (pcm.astype(np.float32) / 32768).mean(axis=1, dtype=np.float32)
    recognizer.transcribe_samples(mono, sample_rate)
    np.testing.assert_array_equal(infer.call_args.args[0], file_features)
    assert np.max(np.abs(file_features)) > 1
    recognizer.close()


