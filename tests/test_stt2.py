def test_fbank_independent_numeric_recipe(identity_frontend: Frontend) -> None:
    """Compare broadband features to a separate double-precision scalar recipe.

    Args:
        identity_frontend:
            Deterministic float32 implementation under test.

    """
    samples = np.random.default_rng(19).standard_normal(880).astype(
        np.float32
    ) * np.float32(0.002)
    reference: list[NDArray[np.float64]] = []
    boundaries = np.linspace(
        1127 * np.log(1 + 20 / 700), 1127 * np.log(1 + 8000 / 700), 82
    )
    frequencies = np.arange(257) * (16000 / 512)
    fft_mel = 1127 * np.log(1 + frequencies / 700)
    triangles = np.stack(
        [
            np.maximum(
                0,
                np.minimum(
                    (fft_mel - boundaries[index])
                    / (boundaries[index + 1] - boundaries[index]),
                    (boundaries[index + 2] - fft_mel)
                    / (boundaries[index + 2] - boundaries[index + 1]),
                ),
            )
            for index in range(80)
        ]
    )
    triangles[:, -1] = 0
    for start in range(0, samples.size - 399, 160):
        frame = samples[start : start + 400].astype(np.float64) * 32768
        frame -= frame.mean()
        frame -= 0.97 * np.concatenate((frame[:1], frame[:-1]))
        power = np.abs(np.fft.rfft(frame * np.hamming(400), n=512)) ** 2
        reference.append(
            np.log(np.maximum(triangles @ power, np.finfo(np.float32).eps))
        )
    np.testing.assert_allclose(
        identity_frontend.fbank(samples), np.stack(reference), atol=5e-5, rtol=5e-6
    )


def _numpy_sanm_reference(
    features: NDArray[np.float32],
    weights: dict[str, NDArray[np.float32]],
    architecture: Architecture,
    language_id: int,
    textnorm_id: int,
) -> NDArray[np.float32]:
    """Evaluate tiny independent NumPy equations for graph numerical qualification.

    Args:
        features:
            Float32 speech matrix shaped (frames, input width).

        weights:
            Tiny seeded checkpoint tensors using the audited key schema.

        architecture:
            Reduced dimensions and block counts for an inexpensive offline test.

        language_id:
            Prefix language embedding row.

        textnorm_id:
            Prefix ITN control row.

    """

    def affine(x: NDArray[np.float32], prefix: str) -> NDArray[np.float32]:
        """Apply a checkpoint-layout affine transformation on the last axis.

        Args:
            x:
                Float32 activation tensor with final feature dimension.

            prefix:
                Module prefix containing weight and bias arrays.

        """
        return x @ weights[f"{prefix}.weight"].T + weights[f"{prefix}.bias"]

    def norm(x: NDArray[np.float32], prefix: str) -> NDArray[np.float32]:
        """Normalize last-axis features with population variance and epsilon 1e-5.

        Args:
            x:
                Float32 activation tensor shaped (frames, width).

            prefix:
                Checkpoint normalization module prefix.

        """
        centered = x - x.mean(axis=-1, keepdims=True)
        normalized = centered / np.sqrt(
            (centered * centered).mean(axis=-1, keepdims=True) + np.float32(1e-5)
        )
        return normalized * weights[f"{prefix}.weight"] + weights[f"{prefix}.bias"]

    a = architecture
    x = np.concatenate(
        (weights["embed.weight"][[language_id, 1, 2, textnorm_id]], features), axis=0
    ) * np.float32(a.hidden_size**0.5)
    positions = np.arange(1, x.shape[0] + 1, dtype=np.float32)[:, None]
    timescales = np.exp(
        np.arange(a.input_size // 2, dtype=np.float32)
        * np.float32(-np.log(np.float32(10000)) / (a.input_size / 2 - 1))
    )
    angles = positions * timescales
    x += np.concatenate((np.sin(angles), np.cos(angles)), axis=1)
    prefixes = ["encoder.encoders0.0"]
    prefixes.extend(f"encoder.encoders.{i}" for i in range(a.encoder_blocks - 1))
    prefixes.extend(f"encoder.tp_encoders.{i}" for i in range(a.tp_blocks))
    for index, prefix in enumerate(prefixes):
        if index == a.encoder_blocks:
            x = norm(x, "encoder.after_norm")
        residual = x
        normalized = norm(x, f"{prefix}.norm1")
        q, k, v = np.split(
            affine(normalized, f"{prefix}.self_attn.linear_q_k_v"), 3, axis=-1
        )
        frames = x.shape[0]
        head_width = a.hidden_size // a.heads
        query = q.reshape(frames, a.heads, head_width).transpose(1, 0, 2)
        key = k.reshape(frames, a.heads, head_width).transpose(1, 0, 2)
        value = v.reshape(frames, a.heads, head_width).transpose(1, 0, 2)
        scores = (query * np.float32(head_width**-0.5)) @ key.transpose(0, 2, 1)
        scores -= scores.max(axis=-1, keepdims=True)
        probabilities = np.exp(scores)
        probabilities /= probabilities.sum(axis=-1, keepdims=True)
        context = (
            (probabilities @ value).transpose(1, 0, 2).reshape(frames, a.hidden_size)
        )
        projected = affine(context, f"{prefix}.self_attn.linear_out")
        padded = np.pad(v, ((a.kernel_size // 2, a.kernel_size // 2), (0, 0)))
        kernel = weights[f"{prefix}.self_attn.fsmn_block.weight"][:, 0, :]
        memory = np.zeros_like(v)
        for tap in range(a.kernel_size):
            memory += padded[tap : tap + frames] * kernel[:, tap]
        attended = projected + memory + v
        if residual.shape[-1] == a.hidden_size:
            attended += residual
        intermediate = affine(
            norm(attended, f"{prefix}.norm2"), f"{prefix}.feed_forward.w_1"
        )
        x = attended + affine(np.maximum(intermediate, 0), f"{prefix}.feed_forward.w_2")
    if a.tp_blocks == 0:
        x = norm(x, "encoder.after_norm")
    return affine(norm(x, "encoder.tp_norm"), "ctc.ctc_lo")


def test_tiny_graph_numerical_parity() -> None:
    """Qualify all SANM equations on a tiny CPU1 graph with two dynamic lengths."""
    # This heavy optional backend is needed only for tiny native graph tests.
    import openvino as ov

    from hoast.stt2.graph import Architecture, build_graph, expected_shapes

    architecture = Architecture(
        input_size=14,
        hidden_size=8,
        heads=2,
        feedforward_size=16,
        encoder_blocks=2,
        tp_blocks=1,
        kernel_size=3,
        vocab_size=19,
    )
    rng = np.random.default_rng(41)
    weights = {
        key: rng.standard_normal(shape).astype(np.float32) * np.float32(0.03)
        for key, shape in expected_shapes(architecture).items()
    }
    for key in weights:
        if ".norm" in key and key.endswith(".weight"):
            weights[key] += 1
    compiled = ov.Core().compile_model(
        build_graph(weights, architecture, output_logits=True),
        "CPU",
        {
            "NUM_STREAMS": 1,
            "INFERENCE_NUM_THREADS": 1,
            "INFERENCE_PRECISION_HINT": "f32",
        },
    )
    request = compiled.create_infer_request()
    for frames in (1, 7):
        features = rng.standard_normal((frames, 14)).astype(np.float32)
        expected = _numpy_sanm_reference(features, weights, architecture, 4, 14)
        request.infer(
            {
                "speech": features[None],
                "language": np.array([4], dtype=np.int64),
                "textnorm": np.array([14], dtype=np.int64),
            }
        )
        np.testing.assert_allclose(
            request.get_tensor("ctc_logits").data[0], expected, atol=2e-5, rtol=2e-5
        )
        np.testing.assert_array_equal(
            request.get_tensor("frame_ids").data[0], expected.argmax(axis=-1)
        )
